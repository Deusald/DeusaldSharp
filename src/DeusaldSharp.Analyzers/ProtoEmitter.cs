using System.Text;

namespace DeusaldSharp.Analyzers;

/// <summary>
/// Emits the source of one proto message. Every type and library call is fully qualified (global::) so user types
/// named like BCL types (Encoding, List, MemoryStream, ...) cannot change the meaning of the generated code.
/// </summary>
internal static class ProtoEmitter
{
    private const string _BASE       = "global::DeusaldSharp.ProtoMsgBase";
    private const string _EXT        = "global::DeusaldSharp.BinaryWriterReaderExtensions";
    private const string _WRITER     = "global::System.IO.BinaryWriter";
    private const string _READER     = "global::System.IO.BinaryReader";
    private const string _LIST       = "global::System.Collections.Generic.List";
    private const int    _INDENT     = 4;

    public static string Generate(ProtoMessageModel model)
    {
        CodeWriter w = new CodeWriter();

        w.Line("// <auto-generated />");
        w.Line("#nullable enable");
        w.Line();

        int opened = 0;

        if (model.Namespace is not null)
        {
            w.Line($"namespace {model.Namespace}");
            w.Open();
            ++opened;
        }

        foreach (string container in model.ContainingDeclarations)
        {
            w.Line(container);
            w.Open();
            ++opened;
        }

        w.Line(model.Declaration);
        w.Open();

        EmitSerialize(w, model);
        w.Line();
        EmitDeserialize(w, model);

        if (model.Fields.Count > 0)
        {
            w.Line();
            EmitReset(w, model);
        }

        w.Close();

        for (int x = 0; x < opened; ++x) w.Close();

        return w.ToString();
    }

    #region Serialize

    private static void EmitSerialize(CodeWriter w, ProtoMessageModel model)
    {
        w.Line($"public override void Serialize({_WRITER} writer)");
        w.Open();
        w.Line("if (!writer.BaseStream.CanSeek)");
        w.Line("    throw new global::System.InvalidOperationException(\"Proto serialization requires a seekable stream (e.g., MemoryStream).\");");

        if (model.Fields.Count > 0)
        {
            w.Line();
            w.Line("long start;");
        }

        foreach (ProtoFieldModel f in model.Fields)
        {
            w.Line();
            w.Line($"// Field {f.Id}: {f.Display}");

            if (f.IsReferenceValue)
            {
                // A null string/Version has no representation: the field is omitted and the reader keeps its default.
                w.Line($"if ({f.Access} is not null)");
                w.Open();
            }

            w.Line($"start = {_BASE}.BeginField(writer, {f.Id});");
            EmitWritePayload(w, f);
            w.Line($"{_BASE}.EndLengthPrefixed(writer, start);");

            if (f.IsReferenceValue) w.Close();
        }

        w.Close();
    }

    private static void EmitWritePayload(CodeWriter w, ProtoFieldModel f)
    {
        string value = f.Access;

        switch (f.Kind)
        {
            case ProtoFieldKind.Primitive:
            case ProtoFieldKind.Special:
            case ProtoFieldKind.SerializableEnum:
                EmitWriteValue(w, f, value);
                return;

            case ProtoFieldKind.NullableValue:
                w.Line($"if ({value}.HasValue)");
                w.Open();
                w.Line("writer.Write(true);");
                EmitWriteValue(w, f, $"{value}.Value");
                w.Close();
                w.Line("else");
                w.Open();
                w.Line("writer.Write(false);");
                w.Close();
                return;

            case ProtoFieldKind.Object:
                // No nested length: the nested message occupies the rest of this field payload.
                w.Line($"{value}.Serialize(writer);");
                return;

            case ProtoFieldKind.NullableObject:
                EmitPresenceOpen(w, value);
                w.Line($"{value}.Serialize(writer);");
                w.Close();
                return;

            case ProtoFieldKind.List:
            case ProtoFieldKind.Array:
                EmitWriteCollection(w, f, value);
                return;

            case ProtoFieldKind.NullableList:
            case ProtoFieldKind.NullableArray:
                EmitPresenceOpen(w, value);
                EmitWriteCollection(w, f, value);
                w.Close();
                return;
        }
    }

    private static void EmitPresenceOpen(CodeWriter w, string value)
    {
        w.Line($"if ({value} is null)");
        w.Open();
        w.Line("writer.Write(false);");
        w.Close();
        w.Line("else");
        w.Open();
        w.Line("writer.Write(true);");
    }

    private static void EmitWriteValue(CodeWriter w, ProtoFieldModel f, string value)
    {
        switch (f.ValueKind)
        {
            case ProtoValueKind.Primitive:
                w.Line($"writer.Write({value});");
                return;
            case ProtoValueKind.Special:
                w.Line($"{_EXT}.Write(writer, {value});");
                return;
            case ProtoValueKind.SerializableEnum:
                w.Line($"{_EXT}.WriteSerializableEnum<{f.ValueType}>(writer, {value});");
                return;
        }
    }

    private static void EmitWriteCollection(CodeWriter w, ProtoFieldModel f, string value)
    {
        bool isList = f.Kind is ProtoFieldKind.List or ProtoFieldKind.NullableList;

        switch (f.ValueKind)
        {
            case ProtoValueKind.Primitive:
                w.Line(isList ? $"{_EXT}.Write(writer, {value});" : $"{_EXT}.WriteArray(writer, {value});");
                return;

            case ProtoValueKind.Special:
                w.Line($"{_EXT}.Write(writer, {value});");
                return;

            case ProtoValueKind.SerializableEnum:
                w.Line(isList
                           ? $"{_EXT}.WriteSerializableEnumList<{f.ValueType}>(writer, {value});"
                           : $"{_EXT}.WriteSerializableEnumArray<{f.ValueType}>(writer, {value});");
                return;

            case ProtoValueKind.Object:
            {
                // count + for each: bool has + int len + bytes
                string count = isList ? $"{value}.Count" : $"{value}.Length";

                w.Line($"writer.Write({count});");
                w.Line($"for (int x = 0; x < {count}; ++x)");
                w.Open();
                w.Line($"{f.ValueType}? item = {value}[x];");
                w.Line("if (item is null)");
                w.Open();
                w.Line("writer.Write(false);");
                w.Line("continue;");
                w.Close();
                w.Line();
                w.Line("writer.Write(true);");
                w.Line($"long itemStart = {_BASE}.BeginLengthPrefixed(writer);");
                w.Line("item.Serialize(writer);");
                w.Line($"{_BASE}.EndLengthPrefixed(writer, itemStart);");
                w.Close();
                return;
            }
        }
    }

    #endregion Serialize

    #region Deserialize

    private static void EmitDeserialize(CodeWriter w, ProtoMessageModel model)
    {
        w.Line($"protected override void DeserializeProtoFields({_READER} reader, long end)");
        w.Open();
        w.Line("while (reader.BaseStream.Position < end)");
        w.Open();
        w.Line($"long fieldEnd = {_BASE}.ReadFieldHeader(reader, end, out ushort id);");

        if (model.Fields.Count > 0)
        {
            w.Line();
            w.Line("switch (id)");
            w.Open();

            for (int x = 0; x < model.Fields.Count; ++x)
            {
                ProtoFieldModel f = model.Fields[x];

                if (x > 0) w.Line();
                w.Line($"case {f.Id}:");
                w.Open();
                EmitReadField(w, f);
                w.Line("break;");
                w.Close();
            }

            w.Close();
        }

        // Unknown fields are skipped; known fields must not read past their declared length.
        w.Line();
        w.Line($"{_BASE}.EndField(reader, id, fieldEnd);");
        w.Close();
        w.Close();
    }

    private static void EmitReadField(CodeWriter w, ProtoFieldModel f)
    {
        string target = f.Access;

        switch (f.Kind)
        {
            case ProtoFieldKind.Primitive:
            case ProtoFieldKind.Special:
            case ProtoFieldKind.SerializableEnum:
                w.Line($"{target} = {ReadValueExpr(f)};");
                return;

            case ProtoFieldKind.NullableValue:
                w.Line("if (reader.ReadBoolean())");
                w.Line($"    {target} = {ReadValueExpr(f)};");
                w.Line("else");
                w.Line($"    {target} = null;");
                return;

            case ProtoFieldKind.Object:
                EmitReadObject(w, f, target);
                return;

            case ProtoFieldKind.NullableObject:
                EmitAbsentBreak(w, target);
                EmitReadObject(w, f, target);
                return;

            case ProtoFieldKind.List:
            case ProtoFieldKind.Array:
                EmitReadCollection(w, f, target);
                return;

            case ProtoFieldKind.NullableList:
            case ProtoFieldKind.NullableArray:
                EmitAbsentBreak(w, target);
                EmitReadCollection(w, f, target);
                return;
        }
    }

    private static void EmitAbsentBreak(CodeWriter w, string target)
    {
        w.Line("if (!reader.ReadBoolean())");
        w.Open();
        w.Line($"{target} = null;");
        w.Line("break;");
        w.Close();
        w.Line();
    }

    private static void EmitReadObject(CodeWriter w, ProtoFieldModel f, string target)
    {
        // The nested message is read in place from the same reader, bounded by the end of this field.
        w.Line($"{f.ValueType} value = new {f.ValueType}();");
        w.Line($"{_BASE}.DeserializeNested(value, reader, fieldEnd);");
        w.Line($"{target} = value;");
    }

    private static void EmitReadCollection(CodeWriter w, ProtoFieldModel f, string target)
    {
        if (f.ValueKind != ProtoValueKind.Object)
        {
            string typeArgs = f.ValueKind == ProtoValueKind.SerializableEnum ? $"<{f.ValueType}>" : "";
            w.Line($"{target} = {_EXT}.{f.CollectionReadMethod}{typeArgs}(reader);");
            return;
        }

        bool   isList         = f.Kind is ProtoFieldKind.List or ProtoFieldKind.NullableList;
        string collectionType = isList ? $"{_LIST}<{f.ValueType}>" : $"{f.ValueType}[]";
        string create         = isList ? $"new {_LIST}<{f.ValueType}>(count)" : $"new {f.ValueType}[count]";

        // Every element takes at least 1 byte (presence flag), so the count is bounded by the field size.
        w.Line($"int count = {_BASE}.ReadCount(reader, fieldEnd, 1);");
        w.Line($"{collectionType} items = {create};");
        w.Line("for (int x = 0; x < count; ++x)");
        w.Open();
        w.Line("if (!reader.ReadBoolean())");
        w.Open();
        if (isList) w.Line("items.Add(null!);");
        w.Line("continue;");
        w.Close();
        w.Line();
        w.Line($"long itemEnd = {_BASE}.ReadLengthPrefix(reader, fieldEnd);");
        w.Line($"{f.ValueType} item = new {f.ValueType}();");
        w.Line($"{_BASE}.DeserializeNested(item, reader, itemEnd);");
        w.Line(isList ? "items.Add(item);" : "items[x] = item;");
        w.Close();
        w.Line($"{target} = items;");
    }

    private static string ReadValueExpr(ProtoFieldModel f)
        => f.ValueKind switch
        {
            ProtoValueKind.Primitive        => $"reader.{f.ReadMethod}()",
            ProtoValueKind.Special          => $"{_EXT}.{f.ReadMethod}(reader)",
            ProtoValueKind.SerializableEnum => $"{_EXT}.ReadSerializableEnum<{f.ValueType}>(reader)",
            _                               => "default!"
        };

    #endregion Deserialize

    #region Reset

    private static void EmitReset(CodeWriter w, ProtoMessageModel model)
    {
        w.Line("protected override void ResetProtoFields()");

        if (!model.CanReset)
        {
            // No parameterless constructor (or required members): fields are not reset.
            w.Line("{ }");
            return;
        }

        // Values of a freshly constructed instance, so field initializers and constructors are respected.
        w.Open();
        w.Line($"{model.FullyQualifiedName} fresh = new {model.FullyQualifiedName}();");

        foreach (ProtoFieldModel f in model.Fields)
            w.Line($"{f.Access} = fresh.{f.Name};");

        w.Close();
    }

    #endregion Reset

    private sealed class CodeWriter
    {
        private readonly StringBuilder _Builder = new StringBuilder();
        private          int           _Depth;

        public void Line(string text = "")
        {
            if (text.Length > 0) _Builder.Append(' ', _Depth * _INDENT).Append(text);
            _Builder.Append('\n');
        }

        public void Open()
        {
            Line("{");
            ++_Depth;
        }

        public void Close()
        {
            --_Depth;
            Line("}");
        }

        public override string ToString() => _Builder.ToString();
    }
}
